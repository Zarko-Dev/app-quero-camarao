const test = require("node:test");
const assert = require("node:assert/strict");

const { shouldUseTextInputMask } = require("../src/utils/shouldUseTextInputMask");

test("shouldUseTextInputMask ignores the default wildcard mask", () => {
    assert.equal(
        shouldUseTextInputMask(
            "****************************************************************************************************************************************************************************************************************************************************************************************************************************************************************************************************************************************************************************************************************************************************************************************************************************************************************************************************************************************************************************************************************************************************************************************************************************************************************************************************************************************",
        ),
        false,
    );
    assert.equal(shouldUseTextInputMask(""), false);
    assert.equal(shouldUseTextInputMask(undefined), false);
});

test("shouldUseTextInputMask enables real masks", () => {
    assert.equal(shouldUseTextInputMask("99/99/9999"), true);
    assert.equal(shouldUseTextInputMask("(99) 99999-9999"), true);
});
